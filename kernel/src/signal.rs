//! Per-process signal bookkeeping.
//!
//! Signals are still delivered at safe points: after a syscall or when a PIT
//! tick interrupts ring 3. This level adds the rest of the basic Unix model:
//! explicit ignore/default dispositions, blocked signals with pending bits,
//! default termination for fatal signals, and pending signals queued by a
//! handler being delivered as soon as that handler calls `sigreturn`.
//!
//! Standard signals coalesce in a pending bitmask. Real-time signals keep one
//! queued [`Siginfo`] per send, so repeated sends arrive in FIFO order with
//! their payload intact.

use core::mem::size_of;

/// Highest signal number accepted by the kernel.
pub const MAX_SIGNAL: u8 = 64;
/// First real-time signal. These signals queue instead of coalescing.
pub const SIGRTMIN: u8 = 34;
/// Last real-time signal.
pub const SIGRTMAX: u8 = MAX_SIGNAL;
/// Maximum number of queued real-time signals held for one process.
pub const MAX_QUEUED_SIGNALS: usize = 64;

/// The mask bit for one signal number.
#[must_use]
pub const fn signal_bit(signum: u8) -> u64 {
    1_u64 << (signum - 1)
}

/// Interrupt from the terminal; terminates by default.
pub const SIGINT: u8 = 2;
/// Illegal instruction; terminates by default.
pub const SIGILL: u8 = 4;
/// Bus error / bad memory access; terminates by default.
pub const SIGBUS: u8 = 7;
/// Arithmetic exception; terminates by default.
pub const SIGFPE: u8 = 8;
/// Kill; cannot be caught, ignored or blocked.
pub const SIGKILL: u8 = 9;
/// User-defined signal 1; ignored by default.
pub const SIGUSR1: u8 = 10;
/// Segmentation fault / invalid memory access; terminates by default.
pub const SIGSEGV: u8 = 11;
/// User-defined signal 2; ignored by default.
pub const SIGUSR2: u8 = 12;
/// Termination request; terminates by default.
pub const SIGTERM: u8 = 15;

/// Reset a signal to its default disposition.
pub const SIG_DFL: u64 = 0;
/// Ignore a signal explicitly.
pub const SIG_IGN: u64 = 1;

/// `siginfo`: sent by `kill` from a user process.
pub const SI_USER: u64 = 1;
/// `siginfo`: sent by `sigqueue` with an explicit value.
pub const SI_QUEUE: u64 = 2;
/// `siginfo`: generated by the kernel.
pub const SI_KERNEL: u64 = 3;
/// `siginfo`: generated by a CPU fault.
pub const SI_FAULT: u64 = 4;

/// Signal information passed to a handler as its third argument.
///
/// The `si_` names are part of the stable clean-room C ABI shared with guests.
#[allow(clippy::struct_field_names)]
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct Siginfo {
    /// The signal number, filled in by the kernel.
    pub si_signo: u64,
    /// One of the `SI_*` codes above.
    pub si_code: u64,
    /// The sending process, or 0 when the kernel sent it.
    pub si_pid: u64,
    /// The value supplied to `sigqueue`.
    pub si_value: u64,
    /// The fault address for synchronous CPU signals.
    pub si_addr: u64,
}

const _: () = assert!(size_of::<Siginfo>() == 40);

impl Siginfo {
    /// Builds the implicit payload for `kill(pid, signum)`.
    #[must_use]
    pub fn user(signum: u8, pid: u64) -> Self {
        Self {
            si_signo: u64::from(signum),
            si_code: SI_USER,
            si_pid: pid,
            si_value: 0,
            si_addr: 0,
        }
    }

    /// Builds the payload for an explicit `sigqueue` value.
    #[must_use]
    pub fn queued(signum: u8, pid: u64, value: u64) -> Self {
        Self {
            si_signo: u64::from(signum),
            si_code: SI_QUEUE,
            si_pid: pid,
            si_value: value,
            si_addr: 0,
        }
    }

    /// Builds the payload for a synchronous CPU fault.
    #[must_use]
    pub fn fault(signum: u8, address: u64) -> Self {
        Self {
            si_signo: u64::from(signum),
            si_code: SI_FAULT,
            si_pid: 0,
            si_value: 0,
            si_addr: address,
        }
    }
}

/// One queued real-time signal.
#[derive(Clone, Copy, Debug, Default)]
struct QueuedSignal {
    signum: u8,
    info: Siginfo,
}

/// How a `queue` call affected the pending signal state.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QueueResult {
    /// The signal is pending and will be delivered.
    Queued,
    /// The disposition discards the signal.
    Ignored,
    /// The bounded real-time queue is full.
    Full,
}

/// What the kernel should do when a pending signal is selected for delivery.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Disposition {
    /// Discard the signal.
    Ignore,
    /// Terminate the process with a negative signal status.
    Terminate,
    /// Enter this user-space handler.
    Handler(u64),
}

/// State owned by one process. It is plain data because the process table lock
/// already serialises every access.
#[derive(Clone, Debug)]
pub struct SignalState {
    pending: u64,
    /// The most recent payload for each standard signal. Real-time signals keep
    /// theirs in `rt_queue`; this lets `sigwaitinfo` report the real sender and
    /// queued value instead of synthesising one at delivery time.
    standard_info: [Siginfo; (SIGRTMIN - 1) as usize],
    handlers: [u64; (MAX_SIGNAL + 1) as usize],
    mask: u64,
    in_handler: bool,
    rt_queue: [QueuedSignal; MAX_QUEUED_SIGNALS],
    rt_head: usize,
    rt_len: usize,
}

impl SignalState {
    /// Creates state with no pending signals and default dispositions.
    #[must_use]
    pub fn new() -> Self {
        Self {
            pending: 0,
            standard_info: core::array::from_fn(|_| Siginfo::default()),
            handlers: [SIG_DFL; (MAX_SIGNAL + 1) as usize],
            mask: 0,
            in_handler: false,
            rt_queue: core::array::from_fn(|_| QueuedSignal::default()),
            rt_head: 0,
            rt_len: 0,
        }
    }

    /// Whether `signum` is a valid signal number.
    #[must_use]
    pub const fn valid(signum: u8) -> bool {
        signum > 0 && signum <= MAX_SIGNAL
    }

    /// The disposition for a signal right now, including its default action.
    #[must_use]
    pub fn disposition(&self, signum: u8) -> Disposition {
        if !Self::valid(signum) {
            return Disposition::Ignore;
        }
        // `SIGKILL` deliberately ignores both handlers and the mask.
        if signum == SIGKILL {
            return Disposition::Terminate;
        }
        match self.handlers[usize::from(signum)] {
            SIG_DFL => Self::default_disposition(signum),
            SIG_IGN => Disposition::Ignore,
            handler => Disposition::Handler(handler),
        }
    }

    /// The default action of a signal without a registered handler.
    const fn default_disposition(signum: u8) -> Disposition {
        match signum {
            SIGINT | SIGILL | SIGBUS | SIGFPE | SIGKILL | SIGSEGV | SIGTERM => {
                Disposition::Terminate
            }
            _ => Disposition::Ignore,
        }
    }

    /// Returns the registered handler address, or 0 when none is installed.
    #[must_use]
    pub fn handler(&self, signum: u8) -> u64 {
        self.handlers[usize::from(signum)]
    }

    /// Installs a disposition and returns the previous one.
    ///
    /// `SIG_DFL` resets to the default action and `SIG_IGN` explicitly ignores
    /// the signal. Installing `SIG_IGN` also drops a signal that was waiting for
    /// the old disposition.
    pub fn set_handler(&mut self, signum: u8, handler: u64) -> u64 {
        if !Self::valid(signum) {
            return u64::MAX;
        }
        let slot = &mut self.handlers[usize::from(signum)];
        let previous = core::mem::replace(slot, handler);
        if handler == SIG_IGN {
            self.pending &= !Self::bit(signum);
            self.discard_rt(signum);
        }
        previous
    }

    /// Whether this signal is currently blocked. `SIGKILL` never is.
    #[must_use]
    pub const fn is_blocked(&self, signum: u8) -> bool {
        if signum == SIGKILL || !Self::valid(signum) {
            return false;
        }
        self.mask & Self::bit(signum) != 0
    }

    /// The current signal mask as one bit per signal (`signum - 1`).
    #[must_use]
    pub const fn mask(&self) -> u64 {
        self.mask
    }

    /// Replaces the mask and returns the previous one. `SIGKILL` is ignored.
    pub fn set_mask(&mut self, mask: u64) -> u64 {
        let previous = self.mask;
        self.mask = mask & !Self::bit(SIGKILL);
        previous
    }

    /// Adds signals to the mask and returns the previous mask.
    pub fn block(&mut self, mask: u64) -> u64 {
        let previous = self.mask;
        self.mask = (previous | mask) & !Self::bit(SIGKILL);
        previous
    }

    /// Removes signals from the mask and returns the previous mask.
    pub fn unblock(&mut self, mask: u64) -> u64 {
        let previous = self.mask;
        self.mask = previous & !mask;
        previous
    }

    /// The pending signals as one bit per signal (`signum - 1`).
    #[must_use]
    pub const fn pending_bits(&self) -> u64 {
        self.pending
    }

    /// Queues a signal that is not being discarded.
    ///
    /// A blocked signal stays pending even when its disposition is ignore: the
    /// process may be waiting for it with `sigwaitinfo`, and delivery will not
    /// consult the handler until the signal is unblocked.
    pub fn queue(&mut self, signum: u8, mut info: Siginfo) -> QueueResult {
        if !Self::valid(signum)
            || (self.disposition(signum) == Disposition::Ignore && !self.is_blocked(signum))
        {
            return QueueResult::Ignored;
        }
        info.si_signo = u64::from(signum);
        if signum >= SIGRTMIN {
            if !self.push_rt(QueuedSignal { signum, info }) {
                return QueueResult::Full;
            }
        } else {
            self.standard_info[usize::from(signum) - 1] = info;
        }
        self.pending |= Self::bit(signum);
        QueueResult::Queued
    }

    /// Drops all queued signals, used when a child is forked.
    pub fn clear_pending(&mut self) {
        self.pending = 0;
        self.rt_head = 0;
        self.rt_len = 0;
        self.in_handler = false;
    }

    /// Takes the next deliverable pending signal.
    ///
    /// Standard signals are taken in ascending order and coalesce. Real-time
    /// signals are taken from their FIFO in send order, including repeated
    /// sends of the same number.
    pub fn take_pending(&mut self) -> Option<(u8, Disposition, Siginfo)> {
        for signum in 1..SIGRTMIN {
            let bit = Self::bit(signum);
            if self.pending & bit != 0 && !self.is_blocked(signum) {
                self.pending &= !bit;
                let info = self.standard_info[usize::from(signum) - 1];
                return Some((signum, self.disposition(signum), info));
            }
        }

        for offset in 0..self.rt_len {
            let entry = self.rt_queue[self.rt_index(offset)];
            if !self.is_blocked(entry.signum) {
                let entry = self.remove_rt(offset);
                if !self.has_rt(entry.signum) {
                    self.pending &= !Self::bit(entry.signum);
                }
                return Some((entry.signum, self.disposition(entry.signum), entry.info));
            }
        }

        // A pending bit without a queued entry can only come from a standard
        // signal path that predates real-time queues. Deliver it safely rather
        // than leaving it pending forever.
        for signum in SIGRTMIN..=MAX_SIGNAL {
            let bit = Self::bit(signum);
            if self.pending & bit != 0 && !self.is_blocked(signum) {
                self.pending &= !bit;
                let info = Siginfo::user(signum, 0);
                return Some((signum, self.disposition(signum), info));
            }
        }
        None
    }

    /// Takes the next pending signal from `mask` for a `sigwaitinfo` caller.
    ///
    /// Unlike [`take_pending`], this ignores dispositions and the current block
    /// mask. A wait caller must block every signal in `mask`, so the kernel must
    /// hand those signals to the waiter instead of a handler. Standard signals
    /// are taken in ascending order; real-time signals follow queue order.
    pub fn take_for_wait(&mut self, mask: u64) -> Option<(u8, Siginfo)> {
        let mask = mask & !Self::bit(SIGKILL);
        for signum in 1..SIGRTMIN {
            let bit = Self::bit(signum);
            if mask & bit != 0 && self.pending & bit != 0 {
                self.pending &= !bit;
                return Some((signum, self.standard_info[usize::from(signum) - 1]));
            }
        }

        for offset in 0..self.rt_len {
            let entry = self.rt_queue[self.rt_index(offset)];
            if mask & Self::bit(entry.signum) != 0 {
                let entry = self.remove_rt(offset);
                if !self.has_rt(entry.signum) {
                    self.pending &= !Self::bit(entry.signum);
                }
                return Some((entry.signum, entry.info));
            }
        }

        // A pending bit without a queued entry should not happen now, but keep
        // the wait path total rather than losing a signal forever.
        for signum in SIGRTMIN..=MAX_SIGNAL {
            let bit = Self::bit(signum);
            if mask & bit != 0 && self.pending & bit != 0 {
                self.pending &= !bit;
                return Some((signum, Siginfo::user(signum, 0)));
            }
        }
        None
    }

    /// Counts pending signals selected by `mask` without consuming them.
    ///
    /// This is how a blocking signal wait decides whether it must sleep. The
    /// check happens under the process-table lock so a sender cannot slip a
    /// signal in between the check and the state change.
    #[must_use]
    pub fn pending_for_mask(&self, mask: u64) -> usize {
        let mask = mask & !Self::bit(SIGKILL);
        let mut count = (1..SIGRTMIN)
            .filter(|&signum| {
                mask & Self::bit(signum) != 0 && self.pending & Self::bit(signum) != 0
            })
            .count();
        count += (0..self.rt_len)
            .filter(|&offset| mask & Self::bit(self.rt_queue[self.rt_index(offset)].signum) != 0)
            .count();
        // Fallback bits without a queued entry are still readable once.
        count += (SIGRTMIN..=MAX_SIGNAL)
            .filter(|&signum| {
                mask & Self::bit(signum) != 0 && self.pending & Self::bit(signum) != 0
            })
            .filter(|&signum| !self.has_rt(signum))
            .count();
        count
    }

    /// Whether a handler is currently running in this process.
    #[must_use]
    pub const fn in_handler(&self) -> bool {
        self.in_handler
    }

    /// Records that a handler has been entered or has returned.
    pub fn set_in_handler(&mut self, value: bool) {
        self.in_handler = value;
    }

    /// The mask bit for a signal number.
    const fn bit(signum: u8) -> u64 {
        signal_bit(signum)
    }

    fn rt_index(&self, offset: usize) -> usize {
        (self.rt_head + offset) % MAX_QUEUED_SIGNALS
    }

    fn push_rt(&mut self, entry: QueuedSignal) -> bool {
        if self.rt_len == MAX_QUEUED_SIGNALS {
            return false;
        }
        self.rt_queue[self.rt_index(self.rt_len)] = entry;
        self.rt_len += 1;
        true
    }

    fn remove_rt(&mut self, offset: usize) -> QueuedSignal {
        let index = self.rt_index(offset);
        let entry = self.rt_queue[index];
        for position in offset + 1..self.rt_len {
            let from = self.rt_index(position);
            let to = self.rt_index(position - 1);
            self.rt_queue[to] = self.rt_queue[from];
        }
        self.rt_len -= 1;
        entry
    }

    fn has_rt(&self, signum: u8) -> bool {
        (0..self.rt_len).any(|offset| self.rt_queue[self.rt_index(offset)].signum == signum)
    }

    fn discard_rt(&mut self, signum: u8) {
        while let Some(offset) =
            (0..self.rt_len).find(|&offset| self.rt_queue[self.rt_index(offset)].signum == signum)
        {
            self.remove_rt(offset);
        }
    }
}

impl Default for SignalState {
    fn default() -> Self {
        Self::new()
    }
}
