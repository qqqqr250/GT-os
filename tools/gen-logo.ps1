<#
.SYNOPSIS
    Regenerates kernel/src/logo_data.rs from tools/logo-source.jpg.

.DESCRIPTION
    Converts the GT logo into a compact 2-bpp bitmap for the framebuffer boot
    screen. The near-white image background becomes transparent (palette 0),
    so the logo blends into the dark console.

    Run it from anywhere:
      powershell -ExecutionPolicy Bypass -File tools\gen-logo.ps1
#>
param(
    [string]$Source = (Join-Path $PSScriptRoot "logo-source.jpg"),
    [string]$Out = (Join-Path $PSScriptRoot "..\kernel\src\logo_data.rs"),
    [int]$Size = 128
)

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing

if (-not (Test-Path $Source)) {
    throw "Missing $Source"
}

# Palette entries 1-3 are the exact dominant colours of the source image.
# Index 0 is the light background and is treated as transparent.
$palette = @(
    @(0xF5, 0xF6, 0xF9),
    @(0xFE, 0xCB, 0x00),
    @(0xF8, 0x04, 0x01),
    @(0x07, 0x30, 0xEA)
)

$image = [System.Drawing.Bitmap]::FromFile($Source)
$scaled = New-Object System.Drawing.Bitmap $Size, $Size
$g = [System.Drawing.Graphics]::FromImage($scaled)
# Nearest-neighbour keeps the thin blue ring, which bicubic blends away.
$g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
$g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
$g.DrawImage($image, 0, 0, $Size, $Size)
$g.Dispose()
$image.Dispose()

$indices = New-Object byte[] ($Size * $Size)
for ($y = 0; $y -lt $Size; $y++) {
    for ($x = 0; $x -lt $Size; $x++) {
        $c = $scaled.GetPixel($x, $y)
        $best = 0
        $bestDist = [double]::PositiveInfinity
        for ($i = 0; $i -lt $palette.Count; $i++) {
            $dr = [int]$c.R - $palette[$i][0]
            $dg = [int]$c.G - $palette[$i][1]
            $db = [int]$c.B - $palette[$i][2]
            $dist = $dr * $dr + $dg * $dg + $db * $db
            if ($dist -lt $bestDist) {
                $bestDist = $dist
                $best = $i
            }
        }
        $indices[$y * $Size + $x] = [byte]$best
    }
}
$scaled.Dispose()

# Pack four 2-bit indices per byte, high bits first, row-major.
$packedCount = [int][Math]::Ceiling(($Size * $Size) / 4.0)
$packed = New-Object byte[] $packedCount
for ($i = 0; $i -lt $indices.Count; $i += 4) {
    $b = 0
    for ($j = 0; $j -lt 4 -and ($i + $j) -lt $indices.Count; $j++) {
        $b = $b -bor ($indices[$i + $j] -shl (6 - 2 * $j))
    }
    $packed[$i / 4] = [byte]$b
}

$lines = @()
for ($i = 0; $i -lt $packedCount; $i += 16) {
    $end = [Math]::Min($i + 15, $packedCount - 1)
    $hex = ($i..$end | ForEach-Object { "0x{0:X2}" -f $packed[$_] }) -join ", "
    $lines += "    $hex,"
}

$body = @"
//! GT logo bitmap, generated by tools/gen-logo.ps1 from tools/logo-source.jpg.
//! Do not edit by hand; re-run the script instead.
//!
//! $Size x $Size pixels, 2 bits per pixel (four colours), row-major.
//! Palette index 0 is transparent (the original light background).

/// Logo width and height in pixels.
pub const LOGO_SIZE: usize = $Size;

/// Packed bytes per bitmap row: ``LOGO_SIZE`` / 4.
pub const ROW_BYTES: usize = $Size / 4;

/// Packed 2-bpp indices: four pixels per byte, high bits first.
pub static LOGO_PIXELS: [u8; $packedCount] = [
$($lines -join "`n")
];
"@

# Rust sources must be BOM-free and LF-terminated or rustfmt rewrites them.
# The here-string has no final newline, so add the one rustfmt expects.
$body = ($body -replace "`r`n", "`n") + "`n"
[System.IO.File]::WriteAllText($Out, $body, (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $Out ($Size x $Size, $packedCount bytes)"
