<#
.SYNOPSIS
    Regenerates kernel/src/font.rs from the public-domain font8x8_basic.h table.

.DESCRIPTION
    The kernel needs glyph bitmaps for the framebuffer console. Rather than
    hand-writing them, this script converts the well-known public-domain 8x8 VGA
    font (Daniel Hepper / Marcel Sondaar / IBM) into a Rust array.

    Run it from anywhere:  powershell -ExecutionPolicy Bypass -File tools\gen-font.ps1
#>
param(
    [string]$Header = (Join-Path $PSScriptRoot "font8x8_basic.h"),
    [string]$Out = (Join-Path $PSScriptRoot "..\kernel\src\font.rs")
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $Header)) {
    throw "Missing $Header. Download it from https://github.com/dhepper/font8x8 (font8x8_basic.h)."
}

$text = Get-Content $Header -Raw

# Each glyph is a brace group with exactly eight 0xNN byte literals.
$pattern = '\{\s*((?:0[xX][0-9a-fA-F]{1,2}\s*,\s*){7}0[xX][0-9a-fA-F]{1,2})\s*\}'
$groups = [regex]::Matches($text, $pattern)
if ($groups.Count -lt 128) {
    throw "Expected 128 glyphs in $Header, found $($groups.Count)."
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("//! 8x8 bitmap font used by the framebuffer console.")
[void]$sb.AppendLine("//!")
[void]$sb.AppendLine('//! Generated by `tools/gen-font.ps1` from `tools/font8x8_basic.h`:')
[void]$sb.AppendLine('//! public-domain 8x8 font by Daniel Hepper, based on Marcel Sondaar / IBM VGA.')
[void]$sb.AppendLine("//! Do not edit by hand; re-run the generator instead.")
[void]$sb.AppendLine()
[void]$sb.AppendLine("/// Glyph cell width in pixels.")
[void]$sb.AppendLine("pub const FONT_WIDTH: usize = 8;")
[void]$sb.AppendLine("/// Glyph cell height in pixels.")
[void]$sb.AppendLine("pub const FONT_HEIGHT: usize = 8;")
[void]$sb.AppendLine()
[void]$sb.AppendLine("/// One `u8` per scanline, least-significant bit is the leftmost pixel.")
[void]$sb.AppendLine("pub static FONT: [[u8; FONT_HEIGHT]; 128] = [")

for ($i = 0; $i -lt 128; $i++) {
    $bytes = $groups[$i].Groups[1].Value -split ',' |
        ForEach-Object { $_.Trim() } |
        Where-Object { $_ -ne '' } |
        ForEach-Object { "0x{0:x2}" -f [Convert]::ToInt32($_, 16) }

    $label = if ($i -ge 32 -and $i -lt 127) { " (" + [char]$i + ")" } else { "" }
    [void]$sb.AppendLine(("    // 0x{0:x2}{1}" -f $i, $label))
    [void]$sb.AppendLine("    [" + ($bytes -join ", ") + "],")
}

[void]$sb.AppendLine("];")

$dir = Split-Path -Parent $Out
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
[System.IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $Out ($($groups.Count) glyphs parsed, 128 emitted)."
